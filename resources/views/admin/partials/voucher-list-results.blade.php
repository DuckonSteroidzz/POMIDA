{{--
    The Vouchers tab's results area: the table (or the empty state) and the
    pager. It is the one part of admin.vouchers that changes when the search box
    or a filter does.

    It is rendered two ways, from the same data and the same controller action
    (AdminController::showVouchers):

      1. Included in the full page, so opening /admin/vouchers?status=active
         directly shows the filtered list with no JavaScript involved.
      2. Returned ALONE when the page's script asks for it in the background
         (header X-Vouchers-Fragment: 1), so a filter change swaps this one
         region instead of reloading the document.

    $vouchers — the already viewer-scoped, filtered, paginated vouchers.
    $filters  — q / status / scope, cleaned by voucherListFilters().

    The wrapper carries data-total and data-filters-on so the page can refresh
    the count badge and the "Clear filters" link, which live outside this
    region (the search box must keep its focus, so it is never swapped).

    Presentation only. This region is generated by a fresh request through the
    normal auth + role middleware, so a supervisor's listing is already narrowed
    to their branch (plus the read-only globals) and staff still get no authoring
    controls. $canManageVoucher mirrors AdminController::promotionScopeRefusal()
    — the button agreeing with the server, never a substitute for it.
--}}
@php
    $adminUser = \Illuminate\Support\Facades\Auth::guard('admin')->user();
    $isAdmin = $adminUser?->isAdmin() ?? false;
    $canAuthorVouchers = $adminUser?->isManager() ?? false;
    $lockedBranchId = \App\Services\AdminOrderAccess::lockedBranchId();

    $canManageVoucher = function ($voucher) use ($canAuthorVouchers, $lockedBranchId) {
        if (! $canAuthorVouchers) {
            return false;
        }

        // Owner — not branch bound, so every voucher, global ones included.
        if ($lockedBranchId === null) {
            return true;
        }

        // Supervisor — own branch only, and never a global voucher. The NULL
        // case is stated on its own for the same reason it is in
        // promotionScopeRefusal(): a coalesced null must not become a match.
        return $voucher->branch_id !== null && (int) $voucher->branch_id === $lockedBranchId;
    };

    $filtersOn = $filters['q'] !== '' || $filters['status'] !== '' || $filters['scope'] !== '';
@endphp
<div id="vchResults" data-testid="voucher-results" data-total="{{ $vouchers->total() }}" data-filters-on="{{ $filtersOn ? '1' : '0' }}">
    @if(count($vouchers) > 0)
    <div class="vch-table-wrap">
        <table class="vch-table">
            <thead>
                <tr>
                    <th>Voucher</th>
                    <th>Discount</th>
                    <th>Usage</th>
                    <th>Min Order</th>
                    <th>Points Req.</th>
                    <th>Valid</th>
                    <th>Scope</th>
                    <th class="is-center">Wheel</th>
                    <th>Status</th>
                    <th class="is-center">Actions</th>
                </tr>
            </thead>
            <tbody>
                @foreach($vouchers as $voucher)
                @php
                    $listStatus = $voucher->listStatus();
                    $statusLabel = ['active' => 'Active', 'inactive' => 'Inactive', 'expired' => 'Expired', 'used_up' => 'Used up'][$listStatus];
                    $onWheel = $voucher->isOnWheel();
                    $usedPct = $voucher->max_uses > 0 ? min(100, (int) round($voucher->used_count / $voucher->max_uses * 100)) : 0;
                    $days = $voucher->daysUntilExpiry();
                    $validFrom = $voucher->valid_from ? \Carbon\Carbon::parse($voucher->valid_from)->format('M d, Y') : null;
                    $expires = $voucher->expires_at ? $voucher->expires_at->format('M d, Y') : null;
                    $issueBlocked = $voucher->issuanceErrorFor();
                    $canManage = $canManageVoucher($voucher);
                    $menuId = 'vchMenu' . $voucher->id;
                @endphp
                <tr data-voucher-row="{{ $voucher->id }}" data-status="{{ $listStatus }}">
                    <td class="vch-cell-voucher">
                        <span class="vch-code">{{ $voucher->code }}</span>
                        <span class="vch-desc">{{ $voucher->description ?: '—' }}</span>
                    </td>
                    <td>
                        <span class="vch-strong">
                            @if($voucher->discount_type === 'fixed')
                            ₱{{ number_format($voucher->discount_value, 2) }}
                            @else
                            {{ $voucher->discount_value }}%
                            @endif
                        </span>
                        <span class="vch-muted">{{ $voucher->discount_type === 'fixed' ? 'Fixed' : 'Percent' }}</span>
                    </td>
                    <td class="vch-cell-usage">
                        <span class="vch-strong">{{ $voucher->used_count }} / {{ $voucher->max_uses > 0 ? $voucher->max_uses : '∞' }}</span>
                        <span class="vch-track" role="progressbar" aria-label="Used" aria-valuemin="0" aria-valuemax="100" aria-valuenow="{{ $usedPct }}">
                            <span class="vch-track-fill {{ $listStatus === 'used_up' ? 'is-full' : '' }}" style="width:{{ $usedPct }}%"></span>
                        </span>
                    </td>
                    <td>₱{{ number_format($voucher->minimum_order, 2) }}</td>
                    <td>{{ $voucher->points_required > 0 ? $voucher->points_required . ' pts' : 'Direct' }}</td>
                    <td class="vch-cell-valid">
                        @if($validFrom && $expires)
                            <span>{{ $validFrom }} – {{ $expires }}</span>
                        @elseif($expires)
                            <span>Until {{ $expires }}</span>
                        @elseif($validFrom)
                            <span>From {{ $validFrom }}</span>
                        @else
                            <span>—</span>
                        @endif
                        @if($days === null)
                            <span class="vch-muted">No expiry</span>
                        @elseif($days < 0)
                            <span class="vch-left is-expired">Expired {{ abs($days) }}d ago</span>
                        @elseif($days === 0)
                            <span class="vch-left is-soon">Last day</span>
                        @else
                            <span class="vch-left {{ $days <= 7 ? 'is-soon' : '' }}">{{ $days }}d left</span>
                        @endif
                    </td>
                    {{-- Same two badges the Menu Items list uses for the same
                         column, so a NULL branch_id reads identically wherever
                         it appears in the portal. --}}
                    <td>
                        @if($voucher->branch_id)
                        <span class="vch-badge is-branch">{{ $voucher->branch->name ?? 'Branch #'.$voucher->branch_id }}</span>
                        @else
                        <span class="vch-badge is-global">Global</span>
                        @endif
                    </td>
                    {{-- Wheel: the RESULT, not a control. A voucher is a Spin &
                         Win prize while it is switched on, has Points Required
                         above 0, and is neither expired nor used up (the same
                         conditions as the prize picker). The one on/off switch
                         that decides it is in Status. --}}
                    <td class="is-center">
                        <span class="vch-switch {{ $onWheel ? 'is-on' : '' }}" role="img"
                            aria-label="{{ $onWheel ? 'On the spin wheel' : 'Not on the spin wheel' }}"
                            title="{{ $onWheel ? 'On the spin wheel' : 'Not on the spin wheel (needs: switched on, Points Required above 0, not expired or used up)' }}"
                            data-wheel="{{ $onWheel ? '1' : '0' }}"></span>
                    </td>
                    <td class="vch-cell-status">
                        <span class="vch-status is-{{ str_replace('_', '-', $listStatus) }}">{{ $statusLabel }}</span>
                        @if($canManage)
                        <form action="{{ route('admin.vouchers.toggle', $voucher->id) }}" method="POST" style="display:inline;margin:0;">
                            @csrf @method('PUT')
                            <button type="submit" class="vch-toggle {{ $voucher->is_active ? 'is-on' : '' }}"
                                role="switch" aria-checked="{{ $voucher->is_active ? 'true' : 'false' }}"
                                aria-label="{{ $voucher->is_active ? 'Switch off' : 'Switch on' }} {{ $voucher->code }}"
                                title="{{ $voucher->is_active ? 'Switched on — click to switch off' : 'Switched off — click to switch on' }}">
                                <span class="vch-toggle-knob"></span>
                            </button>
                        </form>
                        @endif
                    </td>
                    {{-- Actions: one three-dot menu holding what each viewer may do. --}}
                    <td class="is-center">
                        <button type="button" class="vch-kebab" data-vch-menu-btn aria-haspopup="menu" aria-expanded="false"
                            aria-controls="{{ $menuId }}" aria-label="Actions for {{ $voucher->code }}">
                            <i class="bi bi-three-dots-vertical" aria-hidden="true"></i>
                        </button>
                        <div class="vch-menu" id="{{ $menuId }}" role="menu" hidden>
                            {{-- The LIMITED row, per voucher. A supervisor gets
                                 Edit only on their OWN branch's vouchers — never
                                 on a global one, never on another branch's.
                                 updateVoucher() enforces the same rule
                                 server-side, which is what actually stops a
                                 crafted PUT. --}}
                            @if($canManage)
                            <button type="button" role="menuitem"
                                class="vch-menu-item"
                                title="Edit voucher"
                                data-id="{{ $voucher->id }}"
                                data-code="{{ $voucher->code }}"
                                data-description="{{ $voucher->description }}"
                                data-discount-type="{{ $voucher->discount_type }}"
                                data-discount-value="{{ $voucher->discount_value }}"
                                data-max-uses="{{ $voucher->max_uses }}"
                                data-minimum-order="{{ $voucher->minimum_order }}"
                                data-valid-from="{{ $voucher->valid_from ? \Carbon\Carbon::parse($voucher->valid_from)->format('Y-m-d') : '' }}"
                                data-expires-at="{{ $voucher->expires_at ? $voucher->expires_at->format('Y-m-d') : '' }}"
                                data-points-required="{{ $voucher->points_required }}"
                                data-is-active="{{ $voucher->is_active ? '1' : '0' }}"
                                data-branch="{{ $voucher->branch_id ?? '' }}"
                                onclick="openEditVoucherModal(this)">
                                <i class="bi bi-pencil-square" aria-hidden="true"></i> Edit
                            </button>
                            @endif
                            {{-- Issue a bearer code for a walk-in customer who has
                                 no account and never played the wheel. Disabled,
                                 with the reason as a tooltip, whenever the voucher
                                 is not currently issuable — the server refuses it
                                 either way (Voucher::issuanceErrorFor), this just
                                 saves the admin a pointless round trip. --}}
                            @if($issueBlocked === null)
                            <form action="{{ route('admin.vouchers.issue-code', $voucher->id) }}" method="POST" style="margin:0;"
                                onsubmit="return confirm('Issue a new code for {{ $voucher->code }}? It counts against this voucher\'s usage limit.')">
                                @csrf
                                <button type="submit" role="menuitem" class="vch-menu-item is-issue" title="Issue a code for a walk-in customer">
                                    <i class="bi bi-ticket-perforated" aria-hidden="true"></i> Issue code
                                </button>
                            </form>
                            @else
                            <button type="button" role="menuitem" class="vch-menu-item is-disabled" disabled title="{{ $issueBlocked }}">
                                <i class="bi bi-ticket-perforated" aria-hidden="true"></i> Issue code
                            </button>
                            @endif
                            @if($isAdmin)
                            <form action="{{ route('admin.vouchers.delete', $voucher->id) }}" method="POST" style="margin:0;" onsubmit="return confirm('Delete voucher {{ $voucher->code }}?')">
                                @csrf @method('DELETE')
                                <button type="submit" role="menuitem" class="vch-menu-item is-danger">
                                    <i class="bi bi-trash" aria-hidden="true"></i> Delete
                                </button>
                            </form>
                            @endif
                        </div>
                    </td>
                </tr>
                @endforeach
            </tbody>
        </table>
    </div>
    @elseif($filtersOn)
    <div class="vch-empty">
        <i class="bi bi-search"></i>
        No vouchers match these filters. <a href="{{ route('admin.vouchers') }}" class="vch-clear-filters" data-vch-clear>Clear filters</a>
    </div>
    @else
    <div class="vch-empty">
        <i class="bi bi-ticket-perforated"></i>
        No vouchers yet.@if($canAuthorVouchers) Create one above!@endif
    </div>
    @endif

    {{-- Real server-side pagination (2026-09-14) — see the matching note in
         admin/completed-orders.blade.php. This list used to load every
         voucher ever minted on every visit. The links are plain hrefs that
         carry the current filters (withQueryString); the page's script turns a
         click into a background swap, and without it they navigate normally. --}}
    @if($vouchers->total() > 0 && ($vouchers->total() > 15 || $vouchers->lastPage() > 1))
    <div class="voucher-pager">
        <span class="voucher-pager-info">
            Showing {{ $vouchers->firstItem() }}–{{ $vouchers->lastItem() }} of {{ $vouchers->total() }} vouchers
        </span>
        <div class="voucher-pager-nav">
            <a href="{{ $vouchers->onFirstPage() ? '#' : $vouchers->previousPageUrl() }}"
                class="voucher-page-btn {{ $vouchers->onFirstPage() ? 'is-disabled' : '' }}"
                @if($vouchers->onFirstPage()) aria-disabled="true" onclick="return false;" @endif>
                <i class="bi bi-chevron-left"></i>
            </a>
            @php
                $vchCurrent = $vouchers->currentPage();
                $vchLast = $vouchers->lastPage();
                $vchPageNumbers = collect();
                for ($i = 1; $i <= $vchLast; $i++) {
                    if ($i === 1 || $i === $vchLast || abs($i - $vchCurrent) <= 1) {
                        $vchPageNumbers->push($i);
                    } elseif ($vchPageNumbers->last() !== '…') {
                        $vchPageNumbers->push('…');
                    }
                }
            @endphp
            @foreach($vchPageNumbers as $vchPageNumber)
                @if($vchPageNumber === '…')
                    <span class="voucher-page-gap">…</span>
                @else
                    <a href="{{ $vouchers->url($vchPageNumber) }}"
                        class="voucher-page-btn {{ $vchPageNumber === $vchCurrent ? 'is-active' : '' }}">{{ $vchPageNumber }}</a>
                @endif
            @endforeach
            <a href="{{ $vouchers->hasMorePages() ? $vouchers->nextPageUrl() : '#' }}"
                class="voucher-page-btn {{ $vouchers->hasMorePages() ? '' : 'is-disabled' }}"
                @if(!$vouchers->hasMorePages()) aria-disabled="true" onclick="return false;" @endif>
                <i class="bi bi-chevron-right"></i>
            </a>
        </div>
    </div>
    @endif
</div>
