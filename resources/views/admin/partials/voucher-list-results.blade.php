{{--
    The Vouchers tab's results area: the table (or the empty state) and the
    pager. It is the one part of admin.vouchers that changes when the search box
    or a filter does.

    It is rendered two ways, from the same data and the same controller action
    (AdminController::showVouchers):

      1. Included in the full page, so opening /admin/vouchers?status=active
         directly shows the filtered list with no JavaScript involved.
      2. Returned ALONE when the page's script asks for it in the background
         (header X-Vouchers-Fragment: 1), so a filter change swaps this one
         region instead of reloading the document.

    $vouchers     — the already viewer-scoped, filtered, paginated vouchers.
    $filters      — q / status / scope, cleaned by voucherListFilters().
    $voucherStats — the four stat-card counts for the viewer's Viewing branch.

    The wrapper carries data-total, data-filters-on and the four counts so the
    page can refresh the count badge, the "Clear filters" link and the stat
    cards, which live outside this region (the search box must keep its focus,
    so it is never swapped).

    Each voucher is drawn twice: a table row (wider screens) and a card (a
    phone, max-width 640px), as in the tester's reference. Only one is ever
    displayed; both carry the same switch and the same ⋮ menu
    (admin/partials/voucher-row-menu), and the page's script keeps the two
    switches of one voucher in step.

    Presentation only. This region is generated by a fresh request through the
    normal auth + role middleware, so a supervisor's listing is already narrowed
    to their branch (plus the read-only globals) and staff still get no authoring
    controls. $canManageVoucher mirrors AdminController::promotionScopeRefusal()
    — the button agreeing with the server, never a substitute for it.
--}}
@php
    $adminUser = \Illuminate\Support\Facades\Auth::guard('admin')->user();
    $isAdmin = $adminUser?->isAdmin() ?? false;
    $canAuthorVouchers = $adminUser?->isManager() ?? false;
    $lockedBranchId = \App\Services\AdminOrderAccess::lockedBranchId();

    $canManageVoucher = function ($voucher) use ($canAuthorVouchers, $lockedBranchId) {
        if (! $canAuthorVouchers) {
            return false;
        }

        // Owner — not branch bound, so every voucher, global ones included.
        if ($lockedBranchId === null) {
            return true;
        }

        // Supervisor — own branch only, and never a global voucher. The NULL
        // case is stated on its own for the same reason it is in
        // promotionScopeRefusal(): a coalesced null must not become a match.
        return $voucher->branch_id !== null && (int) $voucher->branch_id === $lockedBranchId;
    };

    $filtersOn = $filters['q'] !== '' || $filters['status'] !== '' || $filters['scope'] !== '';
    $statusLabels = ['active' => 'Active', 'inactive' => 'Inactive', 'expired' => 'Expired', 'used_up' => 'Used up'];

    // Everything one voucher's row and card both print, worked out once.
    $present = function ($voucher) use ($canManageVoucher, $canAuthorVouchers, $statusLabels) {
        $canManage = $canManageVoucher($voucher);
        $listStatus = $voucher->listStatus();
        $days = $voucher->daysUntilExpiry();
        $pointsVoucher = (int) $voucher->points_required > 0;

        // The Wheel switch. ON = switched onto the wheel (vouchers.on_wheel).
        // A 0-point voucher is never a prize, so it reads OFF. Disabled, with
        // the reason as its tooltip, wherever the server would refuse it.
        if (! $canManage) {
            $wheelTitle = $canAuthorVouchers
                ? 'Company-wide vouchers can only be changed by the owner.'
                : 'View only';
        } elseif (! $pointsVoucher) {
            $wheelTitle = \App\Models\Voucher::WHEEL_NEEDS_POINTS;
        } else {
            $wheelTitle = 'On: eligible for Spin & Win · Off: excluded';
        }

        if ($days === null) {
            $left = ['No expiry', 'is-none'];
        } elseif ($days < 0) {
            $left = ['Expired ' . abs($days) . 'd ago', 'is-expired'];
        } elseif ($days === 0) {
            $left = ['Expires today', 'is-soon'];
        } elseif ($days <= 7) {
            $left = ['⚠ ' . $days . 'd left', 'is-soon'];
        } else {
            $left = [$days . 'd left', ''];
        }

        return [
            'canManage'    => $canManage,
            'listStatus'   => $listStatus,
            'statusClass'  => str_replace('_', '-', $listStatus),
            'statusLabel'  => $statusLabels[$listStatus],
            'usedPct'      => $voucher->max_uses > 0 ? min(100, (int) round($voucher->used_count / $voucher->max_uses * 100)) : 0,
            'usage'        => $voucher->used_count . ' / ' . ($voucher->max_uses > 0 ? $voucher->max_uses : '∞'),
            'discount'     => $voucher->discount_type === 'fixed' ? '₱' . number_format($voucher->discount_value, 2) : rtrim(rtrim((string) $voucher->discount_value, '0'), '.') . '%',
            'discountType' => $voucher->discount_type === 'fixed' ? 'Fixed' : 'Percent',
            'minOrder'     => (float) $voucher->minimum_order > 0 ? '₱' . number_format($voucher->minimum_order, 2) : '—',
            'points'       => $pointsVoucher ? $voucher->points_required . ' pts' : '—',
            'validFrom'    => $voucher->valid_from ? \Carbon\Carbon::parse($voucher->valid_from)->format('M d, Y') : '—',
            'expires'      => $voucher->expires_at ? $voucher->expires_at->format('M d, Y') : '—',
            'left'         => $left,
            'wheelOn'      => $voucher->on_wheel && $pointsVoucher,
            'wheelEnabled' => $canManage && $pointsVoucher,
            'wheelTitle'   => $wheelTitle,
            'wheelPaused'  => $voucher->wheelPausedReason(),
            'issueBlocked' => $voucher->issuanceErrorFor(),
        ];
    };
@endphp
<div id="vchResults" data-testid="voucher-results" data-total="{{ $vouchers->total() }}" data-filters-on="{{ $filtersOn ? '1' : '0' }}"
    @isset($voucherStats) data-stat-total="{{ $voucherStats['total'] }}" data-stat-active="{{ $voucherStats['active'] }}" data-stat-on-wheel="{{ $voucherStats['on_wheel'] }}" data-stat-expired="{{ $voucherStats['expired'] }}" @endisset>
    @if(count($vouchers) > 0)
    @php $shown = $vouchers->getCollection()->mapWithKeys(fn ($voucher) => [$voucher->id => $present($voucher)]); @endphp
    <div class="vch-table-wrap">
