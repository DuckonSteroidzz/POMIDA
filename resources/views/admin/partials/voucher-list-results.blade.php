                    </td>
                    {{-- Same two words the Menu Items list uses for a NULL vs a
                         set branch_id, so a scope reads identically wherever it
                         appears in the portal. --}}
                    <td>
                        @if($voucher->branch_id)
                        <span class="vch-badge is-branch"><span aria-hidden="true">📍</span> {{ $voucher->branch->name ?? 'Branch #'.$voucher->branch_id }}</span>
                        @else
                        <span class="vch-badge is-global"><span aria-hidden="true">🌐</span> Global</span>
                        @endif
                    </td>
                    {{-- Wheel: include this voucher on Spin & Win (on_wheel).
                         A real switch since Oct 2026 — the page's script sends
                         it to admin.vouchers.wheel. It is one condition of
                         being a prize; the note says when another one (off,
                         expired, used up) is holding it back. --}}
                    <td class="vch-cell-wheel">
                        <x-admin.on-off-switch :checked="$p['wheelOn']" :disabled="! $p['wheelEnabled']"
                            :title="$p['wheelTitle']" label="Spin wheel for {{ $voucher->code }}"
                            data-vch-wheel="{{ $voucher->id }}" data-code="{{ $voucher->code }}"
                            :data-url="$p['wheelEnabled'] ? route('admin.vouchers.wheel', $voucher->id) : null" />
                        <span class="vch-wheel-note" data-vch-wheel-note="{{ $voucher->id }}" @if(! $p['wheelPaused']) hidden @endif>{{ $p['wheelPaused'] }}</span>
                    </td>
                    {{-- Status: the badge alone. Activate / Deactivate is in
                         the ⋮ menu, as in the reference. --}}
                    <td class="vch-cell-status">
                        <span class="vch-status is-{{ $p['statusClass'] }}">{{ $p['statusLabel'] }}</span>
                    </td>
                    <td class="vch-cell-actions">
                        <button type="button" class="vch-kebab" data-vch-menu-btn aria-haspopup="menu" aria-expanded="false"
                            aria-controls="vchMenu{{ $voucher->id }}" aria-label="Actions for {{ $voucher->code }}" title="More actions">
                            <span aria-hidden="true">⋮</span>
                        </button>
                        @include('admin.partials.voucher-row-menu', ['menuId' => 'vchMenu' . $voucher->id, 'canManage' => $p['canManage'], 'issueBlocked' => $p['issueBlocked']])
                    </td>
                </tr>
                @endforeach
            </tbody>
        </table>
    </div>

    {{-- A phone: one card per voucher instead of a sideways-scrolling table. --}}
    <div class="vch-cards" data-testid="voucher-cards">
        @foreach($vouchers as $voucher)
        @php $p = $shown[$voucher->id]; @endphp
        <article class="vch-mc" data-voucher-card="{{ $voucher->id }}">
            <div class="vch-mc-top">
                <div class="vch-mc-name">
                    <span class="vch-code">{{ $voucher->code }}</span>
                    <span class="vch-desc">{{ $voucher->description ?: '—' }}</span>
                </div>
                <span class="vch-status is-{{ $p['statusClass'] }}">{{ $p['statusLabel'] }}</span>
            </div>
            <dl class="vch-mc-dl">
                <div><dt>Discount</dt><dd>{{ $p['discount'] }} <span class="vch-muted">{{ $p['discountType'] }}</span></dd></div>
                <div><dt>Usage</dt><dd>{{ $p['usage'] }}<span class="vch-track"><span class="vch-track-fill {{ $p['listStatus'] === 'used_up' ? 'is-full' : '' }}" style="width:{{ $p['usedPct'] }}%"></span></span></dd></div>
                <div><dt>Min order</dt><dd>{{ $p['minOrder'] }}</dd></div>
                <div><dt>Points</dt><dd>{{ $p['points'] }}</dd></div>
                <div><dt>Valid</dt><dd>{{ $p['validFrom'] }} – {{ $p['expires'] }}</dd></div>
                <div><dt>Expiry</dt><dd class="vch-left {{ $p['left'][1] }}">{{ $p['left'][0] }}</dd></div>
                <div><dt>Scope</dt><dd>
                    @if($voucher->branch_id)
                    <span class="vch-badge is-branch"><span aria-hidden="true">📍</span> {{ $voucher->branch->name ?? 'Branch #'.$voucher->branch_id }}</span>
                    @else
                    <span class="vch-badge is-global"><span aria-hidden="true">🌐</span> Global</span>
                    @endif
                </dd></div>
                <div><dt>Spin Wheel</dt><dd>
                    <x-admin.on-off-switch :checked="$p['wheelOn']" :disabled="! $p['wheelEnabled']"
                        :title="$p['wheelTitle']" label="Spin wheel for {{ $voucher->code }}"
                        data-vch-wheel="{{ $voucher->id }}" data-code="{{ $voucher->code }}"
                        :data-url="$p['wheelEnabled'] ? route('admin.vouchers.wheel', $voucher->id) : null" />
                    <span class="vch-wheel-note" data-vch-wheel-note="{{ $voucher->id }}" @if(! $p['wheelPaused']) hidden @endif>{{ $p['wheelPaused'] }}</span>
                </dd></div>
            </dl>
            <div class="vch-mc-actions">
                <button type="button" class="vch-kebab" data-vch-menu-btn aria-haspopup="menu" aria-expanded="false"
                    aria-controls="vchMenuM{{ $voucher->id }}" aria-label="Actions for {{ $voucher->code }}" title="More actions">
                    <span aria-hidden="true">⋮</span>
                </button>
                @include('admin.partials.voucher-row-menu', ['menuId' => 'vchMenuM' . $voucher->id, 'canManage' => $p['canManage'], 'issueBlocked' => $p['issueBlocked']])
            </div>
        </article>
        @endforeach
    </div>
    @elseif($filtersOn)
    <div class="vch-empty">
        <i class="bi bi-search"></i>
        No vouchers match these filters. <a href="{{ route('admin.vouchers') }}" class="vch-clear-filters" data-vch-clear>Clear filters</a>
    </div>
    @else
    <div class="vch-empty">
        <i class="bi bi-ticket-perforated"></i>
        No vouchers yet.@if($canAuthorVouchers) Create one above!@endif
    </div>
    @endif

    {{-- Real server-side pagination (2026-09-14) — see the matching note in
         admin/completed-orders.blade.php. This list used to load every
         voucher ever minted on every visit. The links are plain hrefs that
         carry the current filters (withQueryString); the page's script turns a
         click into a background swap, and without it they navigate normally. --}}
    @if($vouchers->total() > 0 && ($vouchers->total() > 15 || $vouchers->lastPage() > 1))
    <div class="voucher-pager">
        <span class="voucher-pager-info">
            Showing {{ $vouchers->firstItem() }}–{{ $vouchers->lastItem() }} of {{ $vouchers->total() }} vouchers
        </span>
        <div class="voucher-pager-nav">
            <a href="{{ $vouchers->onFirstPage() ? '#' : $vouchers->previousPageUrl() }}"
                class="voucher-page-btn {{ $vouchers->onFirstPage() ? 'is-disabled' : '' }}"
                @if($vouchers->onFirstPage()) aria-disabled="true" onclick="return false;" @endif>
                <i class="bi bi-chevron-left"></i>
            </a>
            @php
                $vchCurrent = $vouchers->currentPage();
                $vchLast = $vouchers->lastPage();
                $vchPageNumbers = collect();
                for ($i = 1; $i <= $vchLast; $i++) {
                    if ($i === 1 || $i === $vchLast || abs($i - $vchCurrent) <= 1) {
                        $vchPageNumbers->push($i);
                    } elseif ($vchPageNumbers->last() !== '…') {
                        $vchPageNumbers->push('…');
                    }
                }
            @endphp
            @foreach($vchPageNumbers as $vchPageNumber)
                @if($vchPageNumber === '…')
                    <span class="voucher-page-gap">…</span>
                @else
                    <a href="{{ $vouchers->url($vchPageNumber) }}"
                        class="voucher-page-btn {{ $vchPageNumber === $vchCurrent ? 'is-active' : '' }}">{{ $vchPageNumber }}</a>
                @endif
            @endforeach
            <a href="{{ $vouchers->hasMorePages() ? $vouchers->nextPageUrl() : '#' }}"
                class="voucher-page-btn {{ $vouchers->hasMorePages() ? '' : 'is-disabled' }}"
                @if(!$vouchers->hasMorePages()) aria-disabled="true" onclick="return false;" @endif>
                <i class="bi bi-chevron-right"></i>
            </a>
        </div>
    </div>
    @endif
