                        <span class="vch-muted">{{ $p['discountType'] }}</span>
                    </td>
                    <td class="vch-cell-usage">
                        <span>{{ $p['usage'] }}</span>
                        <span class="vch-track" role="progressbar" aria-label="Used" aria-valuemin="0" aria-valuemax="100" aria-valuenow="{{ $p['usedPct'] }}">
                            <span class="vch-track-fill {{ $p['listStatus'] === 'used_up' ? 'is-full' : '' }}" style="width:{{ $p['usedPct'] }}%"></span>
